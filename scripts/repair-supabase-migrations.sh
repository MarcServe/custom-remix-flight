#!/usr/bin/env bash
# Repair remote migration history: mark versions that exist on remote but have no
# matching local file as "reverted" so that `supabase db push` can run.
# Run from project root: ./scripts/repair-supabase-migrations.sh
# You will be prompted for your database password.

set -e
cd "$(dirname "$0")/.."

# Versions from "Remote migration versions not found in local migrations directory"
REVERT_VERSIONS="20251031014752 20251031020940 20251031034829 20251031040723 20251031045416 20251031051636 20251031053832 20251031063150 20251031080933 20251031084412 20251101003406 20251101112827 20251101113023 20251101120825 20251101122220 20251101123023 20251101130330 20251101131626 20251101131940 20251101132429 20251101133145 20251101133609 20251101153157 20251101154729 20251101154923 20251101155047 20251101155243 20251101161911 20251101212822 20251101212922 20251101214337 20251101214557 20251101215156 20251101221122 20251101221430 20251101222020 20251102011038 20251102015545 20251102023650 20251102033330 20251102043205 20251102043223 20251102043655 20251102065040 20251102090228 20251102093946 20251102135747 20251103003627 20251103005614 20251103050528 20251103051447 20251103052124 20251103052146 20251103052229 20251103053220 20251103053234 20251103053710 20251103054341 20251103082346 20251103101108 20251103102226 20251103104523 20251109021517 20251231151928 20260114060947 20260114063022 20260114223218 20260115204959 20260119164903 20260121020308"

echo "Repairing migration history (marking ${REVERT_VERSIONS// /, } as reverted)..."
npx supabase migration repair --status reverted $REVERT_VERSIONS

echo ""
echo "Done. Run 'npx supabase db push' to apply pending local migrations."
echo "If push fails with 'relation already exists', those migrations are already applied;"
echo "you can mark them applied with: supabase migration repair --status applied <version>"
